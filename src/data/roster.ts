/** "https://www.youtube.com/@TomoyTom/featured" -> "@TomoyTom" */
export function youtubeHandle(url: string) {
  const match = url.match(/youtube\.com\/(@[^/?#]+)/i)
  return match ? match[1] : url
}

/** "https://www.instagram.com/octoramonth/" -> "@octoramonth" */
export function instagramHandle(url: string) {
  const match = url.match(/instagram\.com\/([^/?#]+)/i)
  return match ? `@${match[1]}` : url
}

export function initials(name: string) {
  return name
    .split(/\s+/)
    .map((part) => part[0])
    .join('')
    .slice(0, 2)
    .toUpperCase()
}
